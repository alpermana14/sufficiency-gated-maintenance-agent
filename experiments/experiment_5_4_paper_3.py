# ===================== FEATURE ENGINEERING =====================
def make_lag_features(df, lag_steps):
    X = df.copy()
    for lag in range(1, lag_steps + 1):
        X = pd.concat([X, df.shift(lag).add_suffix(f"_lag{lag}")], axis=1)
    return X.dropna()

# ===================== MODEL TRAINING =====================
def train_models(X_train, y_train, X_val, y_val):
    models = {}
    params = {
        "objective": "regression",
        "metric": "rmse",
        "learning_rate": 0.05,
        "num_leaves": 31,
        "verbosity": -1,
        "seed": 42,
    }

    for tgt in TARGETS:
        train_set = lgb.Dataset(X_train, y_train[tgt])
        val_set = lgb.Dataset(X_val, y_val[tgt])

        model = lgb.train(
            params,
            train_set,
            valid_sets=[val_set],
            num_boost_round=500,
            callbacks=[lgb.early_stopping(20)]
        )
        models[tgt] = model

    return models

# ===================== FORECASTING LOGIC =====================
def generate_forecast(models, df, X_cols):
    """Recursive forecasting loop."""
    buffer = df.iloc[-LAG_STEPS:].copy()
    future_index = pd.date_range(
        start=df.index[-1] + pd.Timedelta(FREQ),
        periods=FORECAST_HORIZON,
        freq=FREQ
    )

    forecast_dict = {tgt: [] for tgt in TARGETS}

    for step in range(FORECAST_HORIZON):
        input_row = {}
        # Reconstruct lag features from buffer
        # Note: X_cols contains names like 'current_lag1', 'temperature_lag2'
        base_cols = [c.split("_lag")[0] for c in X_cols if "_lag" in c]
        base_cols = list(set(base_cols)) # unique

        for col in base_cols:
            if col in buffer.columns:
                for lag in range(1, LAG_STEPS + 1):
                    lag_col = f"{col}_lag{lag}"
                    if lag_col in X_cols:
                         # Get value from buffer (lag steps back)
                         # iloc[-1] is most recent, iloc[-lag] goes back
                         input_row[lag_col] = buffer.iloc[-lag][col]

        # Create single-row DataFrame for prediction
        X_pred = pd.DataFrame([input_row]).reindex(columns=X_cols).fillna(0)

        # Predict all targets for this step
        preds_step = {}
        for tgt in TARGETS:
            val = float(models[tgt].predict(X_pred)[0])
            preds_step[tgt] = val
            forecast_dict[tgt].append(val)

        # Update buffer with predicted values for next recursion
        new_row = buffer.iloc[-1].copy()
        for tgt in TARGETS:
            new_row[tgt] = preds_step[tgt]

        buffer = pd.concat([buffer, new_row.to_frame().T])
        buffer = buffer.iloc[-LAG_STEPS:] # Keep buffer size constant

    # Convert to DataFrame
    forecast_df = pd.DataFrame(forecast_dict, index=future_index)
    return forecast_df

# ===================== ANOMALY DETECTION (IDK) =====================

def detect_anomalies(df):
    """Runs IDK sliding window on all targets."""
    idk_scores = {}
    N = IDK_LOOKBACK  # Lookback window (144 = approx 3 days of 30min data)

    for sig in TARGETS:
        # Prepare data shape for IDK
        X = np.array(df[sig]).reshape(-1, 1)
        X = X[-min(len(X), N):]

        # Debugging: Print stats of X
        print(f"\n--- Data for {sig} before IDK ---")
        print(f"Min: {np.min(X):.4f}, Max: {np.max(X):.4f}, Mean: {np.mean(X):.4f}, Std: {np.std(X):.4f}")
        print(f"Shape: {X.shape}, All values same: {np.all(X == X[0])}")

        # Run IDK
        # Using the imported IDK_square_sliding function
        scores = IDK_square_sliding(
            X,
            t=100,
            psi1=IDK_PSI,
            width=IDK_WIDTH,
            psi2=IDK_PSI
        )
        idk_scores[sig] = scores.flatten()

    return idk_scores

# ===================== MAIN PIPELINE =====================
def run_pipeline(df_input):
    """Orchestrator function called by main.py."""
    df = df_input.copy() # Work on a copy

    print("[INFO] Preprocessing input DataFrame...")
    # Timestamps are brought to Asia/Singapore (UTC+8), the plant's local time and
    # the time base the manuscript reports. A UTC source is shifted; a source that
    # is already local is only labelled. Localising a UTC source directly to +8
    # would relabel without shifting and place the 5 May load onset eight hours early.
    if SOURCE_TZ == "utc":
        df["datetime"] = pd.to_datetime(
            df["datetime"], dayfirst=True, utc=True
        ).dt.tz_convert("Asia/Singapore")
    else:
        df["datetime"] = pd.to_datetime(df["datetime"]).dt.tz_localize("Asia/Singapore")

    if FIG5_END:
        cutoff = pd.Timestamp(FIG5_END, tz="Asia/Singapore")
        df = df[df["datetime"] <= cutoff]
        print(f"[INFO] truncated at {cutoff}, {len(df)} records remain")

    # A re-exported CSV may already carry imputation flags; drop them so they are
    # recomputed here and never reach the numeric interpolation as object columns.
    df = df.drop(columns=[c for c in df.columns if c.endswith("_error_flag")])

    # Round datetime to 30min intervals and set as index
    df["datetime"] = df["datetime"].dt.round("30min")
    df = df.groupby("datetime").first().resample("30min").asfreq()

    # Ensure numeric columns are actually numeric, coercing errors
    for col in TARGETS:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors='coerce')

    # Drop non-numeric/non-target columns before imputation and feature engineering
    cols_to_drop_before_imputation = ["conveyor_id", "category", "status"]
    df = df.drop(columns=[c for c in cols_to_drop_before_imputation if c in df.columns])

    # Apply imputation
    df = apply_imputation(df, TARGETS)

    # Clean columns (round to 2 decimal places)
    # The original load_conveyor_data also dropped conveyor_id and category here, but they should be gone already
    df = df.round(2)

    print("[INFO] Feature Engineering...")
    df_numeric = df[TARGETS].copy()
    data = make_lag_features(df_numeric, LAG_STEPS)
    X = data.drop(columns=TARGETS)
    y = data[TARGETS]

    # Split (Simple 80/20 for retraining)
    split_idx = int(len(X) * 0.9)
    X_train, X_val = X.iloc[:split_idx], X.iloc[split_idx:]
    y_train, y_val = y.iloc[:split_idx], y.iloc[split_idx:]

    print("[INFO] Training Models...")
    models = train_models(X_train, y_train, X_val, y_val)

    print("[INFO] Generating Forecast...")
    forecast_df = generate_forecast(models, df, X.columns)

    print("[INFO] Detecting Anomalies...")
    anomalies = detect_anomalies(df)

    # Calculate Feature Importance (Optional, simplified)
    importance = {}
    for tgt in TARGETS:
        imp = models[tgt].feature_importance()
        names = models[tgt].feature_name()
        # Return top 10 as list of dicts
        sorted_idx = np.argsort(imp)[::-1][:10]
        importance[tgt] = [{"feature": names[i], "importance": float(imp[i])} for i in sorted_idx]

    return df, forecast_df, anomalies, importance, models

# Run the full pipeline
print(f"[INFO] s-IDK^2 psi={IDK_PSI}, width={IDK_WIDTH}, lookback={IDK_LOOKBACK} records")
